"""Generate a synthetic fsaverage5-like surface for smoke testing.

This bypasses FastSurfer for the MVP. We attempt to load the fsaverage5
sphere mesh that ships with FreeSurfer, and assign synthetic per-vertex
features that have realistic distributions matching FreeSurfer outputs:
  - sulc: zero-mean, std~0.5, smooth on the sphere
  - curv: zero-mean, std~0.3, smooth on the sphere
  - thickness: 2-4 mm, smooth on the sphere

Without FreeSurfer installed, we fall back to a 10K-vertex icosphere
(fsaverage5 resolution) generated by trimesh.

For Phase 2, this is replaced by real FastSurfer outputs.
"""
import os
from pathlib import Path

import numpy as np

OUT_DIR = Path(__file__).parent.parent / "data" / "synthetic_surface"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def main():
    # Load fsaverage5 sphere mesh
    # Standard FreeSurfer install path:
    fs_home = Path(os.environ.get("FREESURFER_HOME", "/usr/local/freesurfer"))
    sphere_lh = fs_home / "subjects" / "fsaverage" / "surf" / "lh.sphere"
    sphere_rh = fs_home / "subjects" / "fsaverage" / "surf" / "rh.sphere"

    for hemi, sphere_path in [("lh", sphere_lh), ("rh", sphere_rh)]:
        if not sphere_path.exists():
            print(f"WARNING: {sphere_path} not found; using standalone ico sphere")
            # Build a standalone ico sphere (no FreeSurfer needed)
            import trimesh
            sphere = trimesh.creation.icosphere(subdivisions=5)  # ~10K vertices
            V = sphere.vertices.astype(np.float32)
            F = sphere.faces
        else:
            from nibabel.freesurfer.io import read_geometry
            V, F = read_geometry(str(sphere_path))
            V = V.astype(np.float32)

        n_verts = V.shape[0]
        print(f"  {hemi}: {n_verts} vertices, {F.shape[0]} faces")

        # Smooth random features (low-frequency spherical harmonics)
        rng = np.random.default_rng(42 if hemi == "lh" else 43)
        rand_feats = rng.standard_normal((n_verts, 16)).astype(np.float32)
        # Build a sparse kNN graph and smooth over it
        from sklearn.neighbors import NearestNeighbors
        knn = NearestNeighbors(n_neighbors=8).fit(V)
        _, neighbors = knn.kneighbors(V)
        # Iterative smoothing (3 rounds)
        for _ in range(3):
            rand_feats = rand_feats[neighbors].mean(axis=1)

        sulc = rand_feats[:, 0] * 0.5  # sulc: zero-mean, std~0.5
        curv = rand_feats[:, 1] * 0.3  # curv: zero-mean, std~0.3
        thickness = 2.5 + rand_feats[:, 2] * 0.5  # thickness: 2-4 mm

        np.savez(
            OUT_DIR / f"synthetic_{hemi}.npz",
            coords=V,
            faces=F,
            sulc=sulc.astype(np.float32),
            curv=curv.astype(np.float32),
            thickness=thickness.astype(np.float32),
        )
        print(f"  Saved: {OUT_DIR / f'synthetic_{hemi}.npz'}")

    print(f"Done. Synthetic surfaces in: {OUT_DIR}")


if __name__ == "__main__":
    main()
